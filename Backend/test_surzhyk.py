def translate_surzhyk(text):
    if not text:
        return text
    words = text.split()
    translated_words = []
    for w in words:
        lower_w = w.lower()
        if lower_w in SURZHYK_DICT:
            trans = SURZHYK_DICT[lower_w]
            if w[0].isupper():
                trans = trans.capitalize()
            translated_words.append(trans)
        else:
            translated_words.append(w)
    return " ".join(translated_words)

